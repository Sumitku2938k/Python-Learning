# Arithmetic Operators
print("num1 + num2 is" , num1 + num2)
print("num1 - num2 is" , num1 - num2)
print("num1 * num2 is" , num1 * num2)
print("num1 / num2 is" , num1 / num2)

print("num1 // num2 is" , num1 // num2) # Remove point ke bad wali value
print("num1 % num2 is" , num1 % num2) # Return remainder after division
print("num1 ** num2 is" , num1 ** num2) # 10^2


